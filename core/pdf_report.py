import os

from datetime import datetime

from reportlab.pdfgen import canvas
from reportlab.lib.pagesizes import A4


def create_report(
    image_path,
    stone_type,
    confidence,
    rgb,
    hardness,
    value_range,
    usage,
    quality
):

    os.makedirs(
        "reports",
        exist_ok=True
    )

    filename = (
        f"reports/Stone_Report_"
        f"{datetime.now():%Y%m%d_%H%M%S}.pdf"
    )

    pdf = canvas.Canvas(
        filename,
        pagesize=A4
    )

    pdf.setTitle(
        "StoneAI Analysis Report"
    )

    # Logo

    try:

        pdf.drawImage(
            "assets/logo.png",
            430,
            760,
            width=120,
            height=50
        )

    except:
        pass

    # Başlık

    pdf.setFont(
        "Helvetica-Bold",
        20
    )

    pdf.drawString(
        50,
        800,
        "STONE AI ANALYSIS REPORT"
    )

    pdf.line(
        50,
        790,
        550,
        790
    )

    # Tarih

    pdf.setFont(
        "Helvetica",
        12
    )

    pdf.drawString(
        50,
        765,
        f"Date: {datetime.now():%d.%m.%Y %H:%M}"
    )

    # Fotoğraf

    try:

        pdf.drawImage(
            image_path,
            50,
            420,
            width=250,
            height=250,
            preserveAspectRatio=True
        )

    except:
        pass

    # Bilgiler

    x = 330

    pdf.setFont(
        "Helvetica-Bold",
        12
    )

    pdf.drawString(
        x,
        700,
        "Stone Type:"
    )

    pdf.drawString(
        x,
        670,
        "Confidence:"
    )

    pdf.drawString(
        x,
        640,
        "RGB:"
    )

    pdf.drawString(
        x,
        610,
        "Hardness:"
    )

    pdf.drawString(
        x,
        580,
        "Estimated Value:"
    )

    pdf.drawString(
        x,
        550,
        "Usage:"
    )

    pdf.drawString(
        x,
        520,
        "Quality Score:"
    )

    pdf.setFont(
        "Helvetica",
        12
    )

    pdf.drawString(
        x + 120,
        700,
        str(stone_type)
    )

    pdf.drawString(
        x + 120,
        670,
        f"%{confidence}"
    )

    pdf.drawString(
        x + 120,
        640,
        str(rgb)
    )

    pdf.drawString(
        x + 120,
        610,
        str(hardness)
    )

    pdf.drawString(
        x + 120,
        580,
        str(value_range)
    )

    pdf.drawString(
        x + 120,
        550,
        str(usage)
    )

    pdf.drawString(
        x + 120,
        520,
        f"{quality}/10"
    )

    # Alt bilgi

    pdf.line(
        50,
        140,
        550,
        140
    )

    pdf.setFont(
        "Helvetica-Oblique",
        10
    )

    pdf.drawString(
        50,
        120,
        "Generated by StoneAI Professional"
    )

    pdf.drawString(
        50,
        100,
        f"Report Time: {datetime.now():%d.%m.%Y %H:%M:%S}"
    )

    pdf.save()

    return filename